create table public.movimientos_stock (
  id            bigint generated always as identity primary key,
  fecha         timestamptz not null default now(),
  producto_id   uuid not null references public.productos(id) on delete restrict,
  ubicacion_id  smallint not null references public.ubicaciones(id),
  tipo          text not null check (tipo in ('ingreso', 'venta', 'ajuste', 'devolucion', 'conteo', 'traslado')),
  cantidad      integer not null check (cantidad <> 0),   -- + entra / - sale
  motivo        text,
  referencia    text,                                   -- nro de remito/factura, etc.
  usuario_id    uuid default auth.uid() references auth.users(id) on delete set null
);
create index movimientos_producto on public.movimientos_stock (producto_id, fecha desc);

-- ---------------------------------------------------------------------
-- LISTAS DE PROVEEDORES (los ~23.000 artículos scrapeados)
-- Sirven para autocompletar al cargar. No son artículos publicados.
-- ---------------------------------------------------------------------
create table public.lista_proveedores (
  proveedor_id  smallint not null references public.proveedores(id) on delete cascade,
  codigo        text not null check (codigo = upper(btrim(codigo)) and codigo <> ''),
  nombre        text not null,
  categoria     text,
  marca         text,
  costo         numeric(12,2) check (costo >= 0),
  actualizado   timestamptz not null default now(),
  busqueda      text generated always as (public.normalizar(nombre || ' ' || codigo)) stored,
  primary key (proveedor_id, codigo)
);
create index lista_proveedores_codigo on public.lista_proveedores (codigo);
create index lista_proveedores_busqueda on public.lista_proveedores using gin (busqueda extensions.gin_trgm_ops);

-- ---------------------------------------------------------------------
-- HISTORIAL GENERAL (quién, qué, cuándo) — lo llenan los triggers
-- ---------------------------------------------------------------------
create table public.historial (
  id           bigint generated always as identity primary key,
  fecha        timestamptz not null default now(),
  usuario_id   uuid,
  usuario      text not null,
  tabla        text not null,
  registro_id  text,
  producto_id  uuid,
  accion       text not null check (accion in ('alta', 'edicion', 'baja')),
  etiqueta     text,
  cambios      jsonb
);
create index historial_fecha    on public.historial (fecha desc);
create index historial_producto on public.historial (producto_id, fecha desc);
