-- ---------------------------------------------------------------------
-- PRODUCTOS
-- SKU propio (PB-000123): nunca cambia, es la identidad del artículo.
-- Los códigos de proveedor y de barras van en la tabla "codigos".
-- ---------------------------------------------------------------------
create sequence public.sku_seq;

create table public.productos (
  id               uuid primary key default gen_random_uuid(),
  sku              text not null unique default ('PB-' || lpad(nextval('public.sku_seq')::text, 6, '0')),
  nombre           text not null check (char_length(btrim(nombre)) between 2 and 200),
  slug             text not null default '',
  descripcion      text check (char_length(descripcion) <= 4000),
  categoria_id     smallint not null references public.categorias(id),
  marca_id         integer references public.marcas(id) on delete set null,
  proveedor_id     smallint references public.proveedores(id) on delete set null,  -- proveedor principal
  -- precios (venta al público, en pesos)
  precio           numeric(12,2) check (precio >= 0),
  precio_anterior  numeric(12,2) check (precio_anterior >= 0),     -- para mostrar tachado en ofertas
  mostrar_precio   boolean not null default false,
  en_oferta        boolean not null default false,
  -- publicación y stock
  estado           text not null default 'publicado' check (estado in ('borrador', 'publicado', 'archivado')),
  disponibilidad   text not null default 'disponible' check (disponibilidad in ('disponible', 'pocas', 'agotado')),
  controla_stock   boolean not null default false,  -- etapa 2: si es true, la disponibilidad sale de los movimientos
  nuevo_hasta      date,
  -- datos útiles para una juguetería (filtros futuros)
  edad_desde_meses smallint check (edad_desde_meses between 0 and 1200),
  edad_hasta_meses smallint check (edad_hasta_meses between 0 and 1200),
  -- búsqueda
  busqueda         text generated always as (public.normalizar(nombre || ' ' || sku || ' ' || coalesce(descripcion, ''))) stored,
  -- auditoría
  creado           timestamptz not null default now(),
  actualizado      timestamptz not null default now(),
  creado_por       uuid default auth.uid() references auth.users(id) on delete set null,
  actualizado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  constraint edades_coherentes check (edad_hasta_meses is null or edad_desde_meses is null or edad_hasta_meses >= edad_desde_meses)
);
create index productos_busqueda_trgm on public.productos using gin (busqueda extensions.gin_trgm_ops);
create index productos_estado_cat   on public.productos (estado, categoria_id);
create index productos_marca        on public.productos (marca_id);
create index productos_proveedor    on public.productos (proveedor_id);
create index productos_actualizado  on public.productos (actualizado desc);

-- Todos los códigos con los que se puede encontrar un artículo:
-- código de barras de la caja, código del proveedor, código viejo del sistema anterior.
create table public.codigos (
  codigo        text primary key check (codigo = upper(btrim(codigo)) and codigo <> ''),
  producto_id   uuid not null references public.productos(id) on delete cascade,
  tipo          text not null check (tipo in ('barras', 'proveedor', 'legado')),
  proveedor_id  smallint references public.proveedores(id) on delete set null,
  creado        timestamptz not null default now(),
  creado_por    uuid default auth.uid() references auth.users(id) on delete set null
);
create index codigos_producto on public.codigos (producto_id);

create table public.imagenes (
  id           uuid primary key default gen_random_uuid(),
  producto_id  uuid not null references public.productos(id) on delete cascade,
  ruta_thumb   text not null check (ruta_thumb !~ '(^/|\.\.|^https?:)'),
  ruta_full    text not null check (ruta_full  !~ '(^/|\.\.|^https?:)'),
  orden        smallint not null default 0,
  ancho        smallint,
  alto         smallint,
  creado       timestamptz not null default now(),
  creado_por   uuid default auth.uid() references auth.users(id) on delete set null,
  unique (producto_id, ruta_thumb)
);
create index imagenes_producto on public.imagenes (producto_id, orden);

create table public.producto_etiquetas (
  producto_id  uuid not null references public.productos(id) on delete cascade,
  etiqueta_id  integer not null references public.etiquetas(id) on delete cascade,
  primary key (producto_id, etiqueta_id)
);

-- Costos: solo admin. Separado para que nunca viaje al catálogo público.
create table public.productos_privado (
  producto_id  uuid primary key references public.productos(id) on delete cascade,
  costo        numeric(12,2) check (costo >= 0),
  notas        text,
  actualizado  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- PRECIOS: historial de cada cambio + registro de aumentos masivos
-- (los aumentos por marca/proveedor/categoría se implementan en etapa 3,
--  pero el historial se empieza a guardar desde el día 1)
-- ---------------------------------------------------------------------
create table public.ajustes_precio (
  id              bigint generated always as identity primary key,
  fecha           timestamptz not null default now(),
  usuario_id      uuid default auth.uid() references auth.users(id) on delete set null,
  descripcion     text not null,                 -- "Aumento Duravit 12%"
  criterio        jsonb not null,                -- {"marca_id": 3} | {"proveedor_id": 1, "categoria_id": 2}
  porcentaje      numeric(6,2) not null,
  redondeo        integer not null default 100,
  cantidad        integer not null default 0,
  revertido       boolean not null default false
);

create table public.historial_precios (
  id           bigint generated always as identity primary key,
  producto_id  uuid not null references public.productos(id) on delete cascade,
  fecha        timestamptz not null default now(),
  precio_antes numeric(12,2),
  precio_nuevo numeric(12,2),
  ajuste_id    bigint references public.ajustes_precio(id) on delete set null,
  usuario_id   uuid default auth.uid() references auth.users(id) on delete set null
);
create index historial_precios_producto on public.historial_precios (producto_id, fecha desc);

