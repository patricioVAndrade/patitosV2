-- 0001 · ESQUEMA BASE
-- Regla de oro: la base es la fuente de la verdad. Las reglas de negocio
-- que no se pueden romper (códigos únicos, precios >= 0, estados válidos)
-- viven acá como restricciones, no solo en la pantalla.
-- =====================================================================

create schema if not exists extensions;
create extension if not exists unaccent with schema extensions;
create extension if not exists pg_trgm  with schema extensions;
grant usage on schema extensions to anon, authenticated, service_role;

-- Texto normalizado para búsquedas: sin tildes y en minúsculas ("Fútbol" = "futbol")
create or replace function public.normalizar(t text)
returns text language sql immutable parallel safe
set search_path = ''
as $$ select lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t, ''))) $$;

create or replace function public.slugify(t text)
returns text language sql immutable parallel safe
set search_path = ''
as $$ select left(trim(both '-' from regexp_replace(public.normalizar(t), '[^a-z0-9]+', '-', 'g')), 80) $$;

